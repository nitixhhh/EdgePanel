def flatten(d):
    p=SP(d); out=[]
    for seg in p:
        if isinstance(seg,Move): out+=[0,seg.end.x,seg.end.y]
        elif isinstance(seg,Line): out+=[1,seg.end.x,seg.end.y]
        elif isinstance(seg,Close): out+=[3]
        elif isinstance(seg,CubicBezier): out+=[2,seg.control1.x,seg.control1.y,seg.control2.x,seg.control2.y,seg.end.x,seg.end.y]
        elif isinstance(seg,QuadraticBezier):
            s,c,e=seg.start,seg.control,seg.end
            c1=(s.x+2/3*(c.x-s.x), s.y+2/3*(c.y-s.y)); c2=(e.x+2/3*(c.x-e.x), e.y+2/3*(c.y-e.y))
            out+=[2,*c1,*c2,e.x,e.y]
        elif isinstance(seg,Arc):
            for cb in seg.as_cubic_curves():
                out+=[2,cb.control1.x,cb.control1.y,cb.control2.x,cb.control2.y,cb.end.x,cb.end.y]
        else: raise Exception(type(seg))
    return out

